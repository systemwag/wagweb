-- Уникальные описания проектных работ + чистка имён заказчиков.
--
-- ПРОБЛЕМА 1. 63 из 100 записей design_projects имели неуникальное описание,
-- из них 52 — дословно одно и то же: «Разработка инструкции по обслуживанию
-- и технического паспорта железнодорожного подъездного пути.» На /design это
-- читается как копипаста, а для поиска — дублирующийся контент.
--
-- ПРОБЛЕМА 2. У 8 записей в поле client зашита дисамбигуация: «ТОО «Рамазан»
-- (дополнение 2)», «ИП «Жанажанов Б.С.» (2)». Из-за этого группировка и
-- фильтр по заказчику показывают их как разные компании.
--
-- РЕШЕНИЕ. Суффикс убирается из client (различать записи достаточно по
-- полю number, оно и печатается в реестре), а описание пересобирается из
-- заказчика и фактического состава работ. Новые факты не вводятся — только
-- то, что уже лежит в самой записи.

-- ─── 1. Суффиксы прочь из имени заказчика ──────────────────────────────
-- Снимаем ровно один хвостовой блок в скобках; имена, где скобки — часть
-- названия компании, не затрагиваются, т.к. таких в таблице нет.
update design_projects
   set client = btrim(regexp_replace(client, '\s*\([^()]*\)\s*$', ''))
 where client ~ '\([^()]*\)\s*$';

-- ─── 2. Пересборка описаний по группам дублей ──────────────────────────
-- Группы определяются текущим (дублирующимся) описанием, поэтому затрагиваются
-- ровно те 63 строки и ни одна лишняя.

update design_projects
   set description =
         'Инструкция о порядке обслуживания и организации движения и технический паспорт '
         || 'железнодорожного подъездного пути ' || client || '.'
 where description = 'Разработка инструкции по обслуживанию и технического паспорта железнодорожного подъездного пути.';

update design_projects
   set description =
         'Инструкция о порядке обслуживания и организации движения и технический паспорт '
         || 'железнодорожного подъездного пути ' || client || ', включая дополнение к инструкции.'
 where description = 'Разработка инструкции и технического паспорта железнодорожного подъездного пути с оформлением дополнения к инструкции.';

update design_projects
   set description = 'Рабочий проект железнодорожного подъездного пути ' || client || '.'
 where description = 'Изготовление рабочего проекта железнодорожного подъездного пути.';

update design_projects
   set description =
         'Разработка технической возможности реконструкции железнодорожного подъездного пути '
         || client || '.'
 where description = 'Разработка технической возможности реконструкции железнодорожного подъездного пути.';

-- Две группы «полного цикла» сводятся к одной формулировке: у всех пяти
-- записей в works есть изыскания, рабочий проект и сопровождение экспертизы.
update design_projects
   set description =
         'Полный цикл проектирования железнодорожного подъездного пути ' || client
         || ' — от инженерных изысканий и рабочего проекта до сопровождения экспертизы '
         || 'в РГП «ГОСЭКСПЕРТИЗА».'
 where description in (
         'Полный цикл проектирования подъездного пути с прохождением государственной экспертизы в РГП «ГОСЭКСПЕРТИЗА».',
         'Полный цикл проектирования железнодорожного подъездного пути с геодезическими изысканиями и государственной экспертизой.'
       );

-- ─── 3. Контроль ───────────────────────────────────────────────────────
-- Ожидается ровно одна оставшаяся пара дублей: ТОО «Делдал», записи № 22 и
-- № 76 — одинаковый заказчик и одинаковый состав работ. Чем они отличаются,
-- по данным в БД установить нельзя, а выдумывать различие нельзя тем более.
do $$
declare
  n int;
begin
  select count(*) into n
    from design_projects d
   where (select count(*) from design_projects e where e.description = d.description) > 1;
  if n > 2 then
    raise exception 'Осталось % строк с неуникальным описанием, ожидалось не более 2', n;
  end if;
end $$;
