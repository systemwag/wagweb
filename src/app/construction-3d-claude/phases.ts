/* ── Хелперы тайминга (без зависимостей) ─────────────────────────────── */
export const clamp01 = (v: number) => Math.min(1, Math.max(0, v));
export const ease = (t: number) => t * t * (3 - 2 * t); // smoothstep
export const lerp = (a: number, b: number, t: number) => a + (b - a) * t;

/** Прогресс фазы i при глобальном p */
export const phaseProgress = (p: number, i: number) =>
  clamp01((p - PHASES[i].start) / (PHASES[i].end - PHASES[i].start));

/** Под-окно [a,b] внутри фазового прогресса q, со сглаживанием */
export const sub = (q: number, a: number, b: number) => ease(clamp01((q - a) / (b - a)));

/** Абсолютное киноокно [a,b] по глобальному p — для сквозных событий */
export const subAbs = (p: number, a: number, b: number) => ease(clamp01((p - a) / (b - a)));

