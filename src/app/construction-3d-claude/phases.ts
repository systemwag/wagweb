/** Суммарная длительность полного проигрывания, с */
export const TOTAL_SEC = RAW.reduce((s, r) => s + r.duration, 0);

export const PHASES: Phase[] = (() => {
  let acc = 0;
  return RAW.map(r => {
    const start = acc / TOTAL_SEC;
    acc += r.duration;
    return { ...r, start, end: acc / TOTAL_SEC };
  });
})();

const BY_ID = Object.fromEntries(PHASES.map(ph => [ph.id, ph])) as Record<PhaseId, Phase>;

export const phaseIndex = (id: PhaseId) => PHASES.findIndex(ph => ph.id === id);

/* ── Хелперы тайминга (без зависимостей) ─────────────────────────────── */
export const clamp01 = (v: number) => Math.min(1, Math.max(0, v));
export const ease = (t: number) => t * t * (3 - 2 * t); // smoothstep
export const lerp = (a: number, b: number, t: number) => a + (b - a) * t;

/** Кадр-независимое сглаживание: доля пути к цели за dt при скорости rate */
export const damp = (rate: number, dt: number) => 1 - Math.exp(-rate * dt);

/** Прогресс этапа id при глобальном p */
export const phaseProgress = (p: number, id: PhaseId) => {
  const ph = BY_ID[id];
  return clamp01((p - ph.start) / (ph.end - ph.start));
};

/** Под-окно [a,b] со сглаживанием — для появления, роста, масштаба */
export const sub = (q: number, a: number, b: number) => ease(clamp01((q - a) / (b - a)));

/** Под-окно БЕЗ сглаживания — для перемещения: машина должна ехать
    с постоянной скоростью, а не разгоняться весь путь по smoothstep */
export const lin = (q: number, a: number, b: number) => clamp01((q - a) / (b - a));

/** Абсолютное окно [a,b] по глобальному p — для сквозных событий */
export const subAbs = (p: number, a: number, b: number) => ease(clamp01((p - a) / (b - a)));

/** Разгон/торможение только на концах: |—/‾‾‾‾‾\—| вместо сплошного
    smoothstep. Скорость — трапеция, значение — пройденный путь, строго
    от 0 до 1.

    Осторожно с нормировкой: на участке торможения вычитается ПОЛНОЕ r,
    а не r/2. С r/2 функция возвращала на выходе 1.21 вместо 1.0, и
    каждая машина проезжала свою точку остановки на 21 % длины пути —
    платформа не доезжала под кран, автомобиль вставал вплотную к
    шлагбауму, укладчик уходил за конец трассы. */
export const travel = (t: number, ramp = 0.12) => {
  const u = clamp01(t);
  if (ramp <= 0) return u;
  const r = Math.min(ramp, 0.49);
  const norm = 1 - r; // средняя скорость на трапеции
  if (u < r) return (u * u) / (2 * r) / norm;
  if (u > 1 - r) {
    const d = 1 - u;
    return (1 - r - (d * d) / (2 * r)) / norm;
  }
  return (u - r / 2) / norm;
};

