/* Модель этапов 3D-полигона.

   ВАЖНО ПРО МОДЕЛЬ ВРЕМЕНИ. Раньше драйвером был скролл: p брался из
   позиции колеса, из-за чего скорость любой машины равнялась скорости
   прокрутки — отсюда «дёрганная» техника. Теперь p двигает транспорт
   воспроизведения (см. useTransport в View.tsx), а доля шкалы у каждого
   этапа ПРОПОРЦИОНАЛЬНА его длительности в секундах. Значит при линейном
   ходе p каждый этап играет ровно свои duration секунд, а «1 единица p»
   везде стоит одинаковое число секунд.

   Мир по-прежнему остаётся чистой функцией p — поэтому перемотка вперёд,
   прыжок на любой этап и reduced-motion получаются простой установкой p. */

