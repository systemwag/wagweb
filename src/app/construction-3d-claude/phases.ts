export const roadY = (x: number) => {
  const d = Math.abs(x - RAIL_X);
  if (d <= DECK_HALF) return DECK_TOP;
  if (d >= RAMP_END) return ASPHALT_TOP;
  return ASPHALT_TOP + (DECK_TOP - ASPHALT_TOP) * ((RAMP_END - d) / RAMP_RUN);
};

