/** Степень «рентгена» в фазе сетей: 0 — обычный вид, 1 — полный разрез.
    Общая для полотна дороги, площадки и ландшафта. */
export const cutaway = (p: number) => {
  const q6 = clamp01((p - PHASES[6].start) / (PHASES[6].end - PHASES[6].start));
  const rise = ease(clamp01((q6 - 0.08) / 0.27));
  const settle = 1 - ease(clamp01((q6 - 0.85) / 0.15)) * 0.4;
  const off = 1 - clamp01((p - PHASES[7].start) / (PHASES[7].end - PHASES[7].start));
  return rise * settle * off;
};

