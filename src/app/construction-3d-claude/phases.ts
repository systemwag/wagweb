/** Степень «рентгена» в фазе сетей: 0 — обычный вид, 1 — полный разрез.
    Общая для полотна дороги, площадки и ландшафта. */
export const cutaway = (p: number) => {
  const q = phaseProgress(p, 'networks');
  const rise = ease(clamp01((q - 0.08) / 0.27));
  // Раньше разрез «оседал» на 40 % к концу этапа, и на финальном общем
  // плане трубы уже не просвечивали сквозь полотно. Держим почти полный
  // рентген до конца — гасит его выход в промышленный этап (off).
  const settle = 1 - ease(clamp01((q - 0.9) / 0.1)) * 0.15;
  /* Полностью разрез не закрываем: в финале карточка обещает «сети под
     нагрузкой», и трубопровод должен просвечивать под полотном вместе
     с бегущими по нему пульсами. Раньше off уходил в ноль, полотно
     становилось глухим и от инженерных сетей в кадре не оставалось
     ничего. */
  const off = 1 - phaseProgress(p, 'industrial') * 0.7;
  return rise * settle * off;
};

